SELECT PERSON_KEY, 'had case' AS src, COUNT(*) AS n
FROM   [RPT].[dbo].[THEATRE_CASE]
WHERE  CASE_STATUS_CAT = 2
  AND  EXISTS (SELECT 1 FROM RPT.dbo.ANAES_RECORD ar WHERE ar.CASE_KEY = THEATRE_CASE.CASE_KEY)
GROUP BY PERSON_KEY
HAVING COUNT(*) > 1
UNION ALL
SELECT v.PERSON_KEY, 'visit only', COUNT(*)
FROM   RPT..VISIT v
       JOIN PERSON_MASTER ON PERSON_MASTER.PERSON_KEY = v.PERSON_KEY
WHERE  v.VISIT_KEY NOT IN (SELECT VISIT_KEY FROM THEATRE_CASE WHERE VISIT_KEY IS NOT NULL)
  AND  SEX_CAT = 2
  AND  ADMIT_TS >= '2025-01-01'
GROUP BY v.PERSON_KEY;
