def _copy_repository(target):
    """A repository that holds the allowlisted public sources, with the planted neonates from which the export takes
    the planted rows, and nothing else."""
    for relative in list(workspace.sources(ROOT)) + [workspace.PLANTED_NEONATES]:
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / relative, destination)
    return target


